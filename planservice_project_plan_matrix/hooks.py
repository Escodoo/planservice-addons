from odoo import Command


def disable_project_milestones(env):
    """Turn off the Milestones project setting and the flag on every project."""
    milestone_group = env.ref("project.group_project_milestone")
    for xmlid in ("base.group_user", "base.group_portal"):
        env.ref(xmlid).write({"implied_ids": [Command.unlink(milestone_group.id)]})
    milestone_group.write({"users": [Command.clear()]})
    env["project.project"].with_context(active_test=False).search(
        [("allow_milestones", "=", True)]
    ).write({"allow_milestones": False})


def link_role_stage(env):
    """Bind the "Cargos" stage created by older versions to the module stage."""
    imd = env["ir.model.data"]
    if imd.search_count(
        [
            ("module", "=", "planservice_project_plan_matrix"),
            ("name", "=", "task_type_role"),
        ]
    ):
        return
    env.cr.execute(
        """
        SELECT id FROM project_task_type
        WHERE name->>'en_US' ILIKE 'cargos' OR name->>'pt_BR' ILIKE 'cargos'
        ORDER BY id LIMIT 1
        """
    )
    row = env.cr.fetchone()
    if row:
        imd.create(
            {
                "module": "planservice_project_plan_matrix",
                "name": "task_type_role",
                "model": "project.task.type",
                "res_id": row[0],
                "noupdate": True,
            }
        )


def link_plan_tasks(env):
    """Link tasks generated by role name to the plan line that generated them."""
    tasks = env["project.task"].with_context(
        active_test=False, skip_hour_plan_generate=True
    )
    lines = env["project.plan.line"].with_context(active_test=False).search([])
    for line in lines:
        if tasks.search_count([("plan_line_id", "=", line.id)]):
            continue
        task = tasks.search(
            [
                ("project_id", "=", line.project_id.id),
                ("name", "=", line.role_id.name),
                ("user_ids", "in", line.user_id.ids),
                ("plan_line_id", "=", False),
            ],
            order="id",
            limit=1,
        )
        task.plan_line_id = line


def post_init_hook(env):
    disable_project_milestones(env)
