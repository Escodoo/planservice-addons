def configure_project_settings(env):
    """Turn Milestones off, as the settings screen does.

    Going through the settings keeps the implied groups consistent and
    updates the flag on every project, instead of emptying the group.
    """
    env["res.config.settings"].create({"group_project_milestone": False}).execute()


# project_status ships no pt_BR translation.
PROJECT_STATUS_PT_BR = {
    "project_status.project_status_pending": "Pendente",
    "project_status.project_status_in_progress": "Em andamento",
    "project_status.project_status_complete": "Concluído",
}


def translate_project_statuses(env):
    """Give the default project statuses their Brazilian Portuguese names."""
    if not env["res.lang"]._lang_get("pt_BR"):
        return
    for xmlid, name in PROJECT_STATUS_PT_BR.items():
        status = env.ref(xmlid, raise_if_not_found=False)
        if status:
            status.with_context(lang="pt_BR").name = name


def allow_replan_on_pending(env):
    """Let Pending projects be re-planned on databases updated to this version.

    The data file sets the flag on install only: it points at a record of
    project_status, which a noupdate file leaves alone on update.
    """
    pending = env.ref("project_status.project_status_pending", raise_if_not_found=False)
    if pending:
        pending.allow_replan = True


def link_role_stage(env):
    """Bind the "Cargos" stage created by older versions to the module stage."""
    imd = env["ir.model.data"]
    if imd.search_count(
        [
            ("module", "=", "planservice_project_plan_matrix"),
            ("name", "=", "task_type_role"),
        ]
    ):
        return
    env.cr.execute(
        """
        SELECT id FROM project_task_type
        WHERE name->>'en_US' ILIKE 'cargos' OR name->>'pt_BR' ILIKE 'cargos'
        ORDER BY id LIMIT 1
        """
    )
    row = env.cr.fetchone()
    if row:
        imd.create(
            {
                "module": "planservice_project_plan_matrix",
                "name": "task_type_role",
                "model": "project.task.type",
                "res_id": row[0],
                "noupdate": True,
            }
        )


def link_plan_tasks(env):
    """Link tasks generated by role name to the plan line that generated them."""
    tasks = env["project.task"].with_context(
        active_test=False, skip_hour_plan_generate=True
    )
    lines = env["project.plan.line"].with_context(active_test=False).search([])
    for line in lines:
        if tasks.search_count([("plan_line_id", "=", line.id)]):
            continue
        task = tasks.search(
            [
                ("project_id", "=", line.project_id.id),
                ("name", "=", line.role_id.name),
                ("user_ids", "in", line.user_id.ids),
                ("plan_line_id", "=", False),
            ],
            order="id",
            limit=1,
        )
        task.plan_line_id = line


def post_init_hook(env):
    configure_project_settings(env)
    translate_project_statuses(env)
